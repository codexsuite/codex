// Generates SeedIds.cs and seedIds.ts from db/seed/ids.csv. No dependencies.
//   node scripts/gen-seed-ids.mjs            write both files
//   node scripts/gen-seed-ids.mjs --check    fail if the committed files differ from the CSV
// The UUID scheme is documented in db/seed/ids.README.md.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = resolve(root, 'db/seed/ids.csv');
const csPath = resolve(root, 'src/Codex.Contracts/SeedIds.cs');
const tsPath = resolve(root, 'src/Codex.Client/src/test-support/seedIds.ts');

const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const kindPattern = /^[a-z][A-Za-z0-9]*$/;
const namePattern = /^[A-Z][A-Za-z0-9]*$/;

export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  const [header, ...body] = rows;
  if (header.join(',') !== 'kind,name,uuid,notes') throw new Error(`Unexpected CSV header: ${header.join(',')}`);
  return body.map(([kind, name, uuid, notes]) => ({ kind, name, uuid, notes }));
}

export function validate(rows) {
  const seenUuids = new Set();
  const seenNames = new Set();
  for (const { kind, name, uuid } of rows) {
    if (!kindPattern.test(kind)) throw new Error(`Bad kind '${kind}'`);
    if (!namePattern.test(name)) throw new Error(`Bad name '${name}' in ${kind}`);
    if (!uuidPattern.test(uuid)) throw new Error(`Bad uuid '${uuid}' for ${kind}.${name}`);
    if (seenUuids.has(uuid)) throw new Error(`Duplicate uuid ${uuid}`);
    if (seenNames.has(`${kind}.${name}`)) throw new Error(`Duplicate name ${kind}.${name}`);
    seenUuids.add(uuid);
    seenNames.add(`${kind}.${name}`);
  }
}

const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const camel = (s) => s[0].toLowerCase() + s.slice(1);

function group(rows) {
  const kinds = new Map();
  for (const row of rows) {
    if (!kinds.has(row.kind)) kinds.set(row.kind, []);
    kinds.get(row.kind).push(row);
  }
  return kinds;
}

export function generate(csvText) {
  const rows = parseCsv(csvText);
  validate(rows);
  const kinds = group(rows);
  const header = 'Generated by scripts/gen-seed-ids.mjs from db/seed/ids.csv. Edit ids.csv and run the script.';

  let cs = `// <auto-generated>\n// ${header}\n// </auto-generated>\n\nnamespace Codex.Contracts;\n\npublic static class SeedIds\n{\n`;
  const csBlocks = [...kinds].map(([kind, items]) => {
    const lines = items.map((r) => `        public static readonly Guid ${r.name} = new("${r.uuid}");`);
    return `    public static class ${pascal(kind)}\n    {\n${lines.join('\n')}\n    }\n`;
  });
  cs += csBlocks.join('\n') + '}\n';

  let ts = `// ${header}\n\nexport const seedIds = {\n`;
  for (const [kind, items] of kinds) {
    ts += `  ${kind}: {\n`;
    for (const r of items) ts += `    ${camel(r.name)}: '${r.uuid}',\n`;
    ts += '  },\n';
  }
  ts += '} as const;\n';
  return { cs, ts };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { cs, ts } = generate(readFileSync(csvPath, 'utf8'));
  if (process.argv.includes('--check')) {
    const stale = [[csPath, cs], [tsPath, ts]].filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text);
    if (stale.length > 0) {
      console.error(`Out of date, run node scripts/gen-seed-ids.mjs: ${stale.map(([p]) => p).join(', ')}`);
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(tsPath), { recursive: true });
    writeFileSync(csPath, cs);
    writeFileSync(tsPath, ts);
  }
}
